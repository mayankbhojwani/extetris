#!/usr/bin/env python3
"""Write docs/api.md from the docstrings in src/extetris.

    python3 tools/make_api_docs.py

The API reference is generated, not hand-written, so it can't drift away from
the code. Re-run this after changing a docstring or a signature.
Uses only the Python standard library (inspect).
"""
import inspect
import sys
from pathlib import Path

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

import extetris  # noqa: E402
from extetris import board, game, generator, mixes, pieces, shape  # noqa: E402
from extetris import designer, playtest, release, variant, window  # noqa: E402

SECTIONS = [
    ("Platform: variants without code", [
        (variant, "Variant"), (designer, "VariantDesigner"),
        (playtest, "playtest"), (playtest, "autoplay"), (playtest, "summary"),
        (release, "build_release")]),
    ("Playing a game", [
        (game, "Game"), (game, "any_piece"), (window, "GameWindow")]),
    ("Choosing pieces (mixes)", [
        (mixes, "mix"), (mixes, "only"), (mixes, "progressive"), (mixes, "mode"),
        (mixes, "MODES"), (mixes, "PieceMix")]),
    ("Pieces", [
        (pieces, "ExTetromino"), (pieces, "NoHole"), (pieces, "OneHole"),
        (pieces, "TwoHole"), (pieces, "ThreeHole"), (pieces, "FourHole"),
        (pieces, "SixHole"), (pieces, "PieceInfo"), (shape, "Shape"),
        (generator, "PieceGenerator")]),
    ("The board", [(board, "Board")]),
]


def doc(obj):
    return inspect.cleandoc(obj.__doc__ or "").strip()


def signature(name, obj):
    try:
        sig = inspect.signature(obj)
        params = [p for p in sig.parameters.values() if p.name not in ("self", "cls")]
        return f"{name}{sig.replace(parameters=params)}"
    except (TypeError, ValueError):
        return name


def block(text):
    return f"```text\n{text}\n```\n" if text else ""


def describe_function(name, fn, level="###"):
    out = [f"{level} `{signature(name, fn)}`\n", block(doc(fn))]
    return "\n".join(o for o in out if o)


def own_members(cls):
    """Public methods/properties defined on this class itself, in source order."""
    items = []
    for name, member in cls.__dict__.items():
        if name.startswith("_") and name != "__init__":
            continue
        items.append((name, member))
    return items


def describe_class(name, cls):
    bases = [b.__name__ for b in cls.__bases__ if b is not object]
    head = f"### class `{name}`" + (f" ({', '.join(bases)})" if bases else "")
    out = [head + "\n", block(doc(cls))]
    for mname, member in own_members(cls):
        if isinstance(member, property):
            out.append(f"- **`{mname}`** (property): {doc(member) or '-'}")
        elif isinstance(member, (staticmethod, classmethod)):
            fn = member.__func__
            kind = "static method" if isinstance(member, staticmethod) else "class method"
            out.append(f"- **`{signature(mname, fn)}`** ({kind}): "
                       f"{doc(fn).splitlines()[0] if doc(fn) else '-'}")
        elif inspect.isfunction(member):
            if mname == "__init__":
                out.append(f"\n**Constructor:** `{signature(name, member)}`\n")
                out.append(block(doc(member)))
            else:
                first = doc(member).splitlines()[0] if doc(member) else "-"
                out.append(f"- **`{signature(mname, member)}`**: {first}")
        elif mname.isupper():
            out.append(f"- **`{mname}`** = `{member!r}`")
    return "\n".join(o for o in out if o) + "\n"


def main():
    out = ["# ExTetris API reference",
           "",
           "_Generated by `python3 tools/make_api_docs.py` from the docstrings "
           "in `src/extetris`. Do not edit by hand._",
           "",
           "For a gentler, example-led introduction see the "
           "[Game Programmer's Manual](manual.md). For how the parts fit "
           "together see the [design document](design.md).",
           "",
           "The system API (pieces, board, game, mixes) is imported with "
           "`from extetris import ...`. The window and platform parts have their "
           "own modules: `extetris.window`, `extetris.variant`, "
           "`extetris.designer`, `extetris.playtest`, `extetris.release`.",
           ""]
    out.append("## Contents\n")
    for title, items in SECTIONS:
        out.append(f"- **{title}:** " + ", ".join(f"`{n}`" for _, n in items))
    out.append("")
    for title, items in SECTIONS:
        out.append(f"## {title}\n")
        for module, name in items:
            obj = getattr(module, name)
            if inspect.isclass(obj):
                out.append(describe_class(name, obj))
            elif callable(obj):
                out.append(describe_function(name, obj))
            else:
                out.append(f"### `{name}`\n")
                if isinstance(obj, dict):
                    out.append("| key | value |\n|---|---|")
                    out.extend(f"| `{k}` | `{v!r}` |" for k, v in obj.items())
                    out.append("")
    unexported = set(extetris.__all__) - {n for _, it in SECTIONS for _, n in it}
    if unexported - {"DIFFICULTY_CLASSES"}:
        raise SystemExit(f"not documented: {sorted(unexported)}")
    path = ROOT / "docs" / "api.md"
    path.write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
